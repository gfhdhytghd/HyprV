#!/usr/bin/env python3
"""Generate parity-host scenes for single widgets from the ORIGINAL quickshell QML.

Input  fixtures/<name>.json (widget fixture, see README.md)
Output <build>/scenes/<name>.qml and <build>/fixtures/<name>.json (parity-host format).

Two kinds:
  "file":   instantiate quickshell/<file> via Qt.createComponent (unmodified file).
  "inline": splice an inline `component X: ...` block VERBATIM out of a quickshell
            file into the scene, so its `root.`/outer-id references resolve against
            the scene root, which carries the shell.qml theme tokens verbatim.
Theme tokens: shell.qml lines from `readonly property real pillOpacity` through
`statsHistoryLimit`, plus withAlpha() and usageSeverityColor(), copied verbatim at
generation time (so a token change in quickshell is picked up automatically).
"""
import json
import re
import sys
from pathlib import Path


def block(text: str, start_pat: str) -> str:
    """Return the brace-balanced block starting at the first line matching start_pat."""
    m = re.search(start_pat, text, re.M)
    if not m:
        raise SystemExit(f"gen.py: pattern not found: {start_pat}")
    i = text.index("{", m.start())
    depth, j = 0, i
    while True:
        c = text[j]
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return text[m.start(): j + 1]
        j += 1


def shell_tokens(src: Path) -> str:
    shell = (src / "shell.qml").read_text()
    lines = shell.splitlines()
    a = next(i for i, l in enumerate(lines) if "readonly property real pillOpacity" in l)
    b = next(i for i, l in enumerate(lines) if "statsHistoryLimit" in l)
    tokens = "\n".join(lines[a: b + 1])
    funcs = block(shell, r"^\s*function withAlpha\(") + "\n" + block(shell, r"^\s*function usageSeverityColor\(")
    return tokens + "\n" + funcs


def main(src: Path, fixture: Path, build: Path) -> None:
    fx = json.loads(fixture.read_text())
    name = fixture.stem
    canvas = fx["canvas"]
    at = fx.get("at", [0, 0])
    bind = fx.get("bind", {})
    extra = fx.get("extra_qml", "")
    imports = ["import QtQuick", "import QtQuick.Effects"] + fx.get("imports", [])

    inline_def = ""
    if fx["kind"] == "inline":
        inl = fx["inline"]
        text = (src / inl["file"]).read_text()
        inline_def = block(text, rf"^\s*component {re.escape(inl['name'])}\s*:")
        type_name = inl["name"]
        # Outer ids used by the inline component are provided by `aliases` in the scene.
        for alias, expr in inl.get("aliases", {}).items():
            extra += f"\n    readonly property var {alias}: {expr}"
        create = None
    else:
        type_name = None
        create = fx["file"]

    bind_lines = "\n".join(f"        {k}: {v}" for k, v in bind.items())
    if create:
        instance = f"""
    property var target: null
    Component.onCompleted: {{
        const c = Qt.createComponent("file://" + Harness.source + "/{create}");
        if (c.status !== Component.Ready) {{ console.error(c.errorString()); Qt.exit(4); return; }}
        target = c.createObject(root, {{ objectName: "target", x: {at[0]}, y: {at[1]}{"".join(", " + k + ": " + v for k, v in bind.items())} }});
    }}"""
    else:
        instance = f"""
    property alias target: target
    {type_name} {{
        id: target
        objectName: "target"
        x: {at[0]}
        y: {at[1]}
{bind_lines}
    }}"""

    scene = f"""{chr(10).join(imports)}

// GENERATED by controls/qml-ref/gen.py from fixture {fixture.name} — do not edit.
Item {{
    id: root
    width: {canvas['width']}
    height: {canvas['height']}
    property bool darkMode: Harness.dark
    property date now: new Date({json.dumps(fx.get('now', '2026-10-23T09:41:00'))})
    readonly property string homeDir: "/nonexistent"
    readonly property string configDir: Harness.source.replace(/\\/[^\\/]+\\/?$/, "")
{shell_tokens(src)}
{extra}

    function resolve(v) {{
        if (typeof v === "string" && v.startsWith("@asset:")) return "file://" + Harness.assets + "/" + v.slice(7);
        if (typeof v === "string" && v.startsWith("@src:")) return "file://" + Harness.source + "/" + v.slice(5);
        if (typeof v === "string" && v.startsWith("@color:")) return Qt.color(v.slice(7));
        return v;
    }}
    function applyProps(map) {{
        for (const k in map) {{
            let v = resolve(map[k]);
            // Fixture props arrive as QVariantList sequences (Array.isArray() === false);
            // components such as SystemTrendChart test Array.isArray, so pass real JS arrays.
            if (v !== null && typeof v === "object" && typeof v.length === "number")
                v = Array.from(v);
            if (k.startsWith("root.")) root[k.slice(5)] = v; else target[k] = v;
        }}
    }}
{inline_def}
{instance}
}}
"""
    (build / "scenes").mkdir(parents=True, exist_ok=True)
    (build / "fixtures" / fx["component"]).mkdir(parents=True, exist_ok=True)
    (build / "scenes" / f"{name}.qml").write_text(scene)
    host_fx = {
        "component": fx["component"],
        "scene": f"{name}.qml",
        "canvas": canvas,
        "fonts": fx.get("fonts", ["JetBrainsMono Nerd Font"]),
        "props": fx.get("props", {}),
        "settle_ms": fx.get("settle_ms", 600),
        "steps": fx.get("steps", [{"capture": ""}]),
        "note": fx.get("note", ""),
    }
    (build / "fixtures" / fx["component"] / f"{name}.json").write_text(json.dumps(host_fx, indent=1))


if __name__ == "__main__":
    main(Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3]))
