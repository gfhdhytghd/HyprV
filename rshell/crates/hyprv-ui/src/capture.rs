// Port of the Qt 6 QImage conversion arithmetic in qdrawhelper_sse4.cpp.
//! Reference capture transport matching Qt 6 QImage's RGBA8 conversion.
//! This changes only PNG serialization, never compositor pixels or blend arithmetic.
use crate::{render::RenderError, skia as sk};

/// Convert one premultiplied RGBA8 pixel using Qt's SSE4 reciprocal/Newton path.
/// Qt's PNG conversion differs from scalar division at exact half ties.
fn straight(pixel: &mut [u8]) {
    let alpha = pixel[3];
    if alpha == 255 {
        return;
    }
    if alpha == 0 {
        pixel.fill(0);
        return;
    }
    #[cfg(target_arch = "x86_64")]
    unsafe {
        use std::arch::x86_64::*;
        let a = _mm_set1_ps(alpha as f32);
        let mut inv = _mm_rcp_ps(a);
        inv = _mm_sub_ps(_mm_add_ps(inv, inv), _mm_mul_ps(inv, _mm_mul_ps(inv, a)));
        inv = _mm_mul_ps(inv, _mm_set1_ps(255.));
        let rgb = _mm_setr_epi32(pixel[0] as i32, pixel[1] as i32, pixel[2] as i32, 0);
        let out = _mm_cvtps_epi32(_mm_mul_ps(_mm_cvtepi32_ps(rgb), inv));
        let mut channels = [0i32; 4];
        _mm_storeu_si128(channels.as_mut_ptr().cast(), out);
        for c in 0..3 {
            pixel[c] = channels[c].clamp(0, 255) as u8;
        }
    }
    #[cfg(not(target_arch = "x86_64"))]
    straight_scalar(pixel);
}

#[cfg(not(target_arch = "x86_64"))]
fn straight_scalar(pixel: &mut [u8]) {
    let a = pixel[3] as u32;
    if a == 255 {
        return;
    }
    if a == 0 {
        pixel.fill(0);
        return;
    }
    let inv = 0x00ff00ff / a;
    for c in &mut pixel[..3] {
        *c = ((*c as u32 * inv + 0x8000) >> 16).min(255) as u8;
    }
}
fn straight_capture(pixels: &mut [u8]) {
    // Qt's SIMD epilogue calls qUnpremultiply_sse4 as well: even a single
    // remaining pixel uses the same reciprocal/Newton arithmetic as full groups.
    for pixel in pixels.chunks_exact_mut(4) {
        straight(pixel);
    }
}

/// Encode a captured image with Qt's QImage premultiplied-to-straight conversion.
/// Use this after the final crop; another premultiplied decode/Skia PNG encode
/// can reintroduce different half-tie rounding. No Qt runtime dependency.
pub fn qt_png(image: &sk::Image) -> Result<Vec<u8>, RenderError> {
    let (w, h) = (image.width(), image.height());
    if w <= 0 || h <= 0 {
        return Err(RenderError::InvalidSize);
    }
    let stride = (w as usize)
        .checked_mul(4)
        .ok_or(RenderError::InvalidSize)?;
    let count = stride
        .checked_mul(h as usize)
        .ok_or(RenderError::InvalidSize)?;
    let mut pixels = vec![0; count];
    let info = sk::ImageInfo::new((w, h), sk::ColorType::RGBA8888, sk::AlphaType::Premul, None);
    if !image.read_pixels(
        &info,
        &mut pixels,
        stride,
        (0, 0),
        sk::image::CachingHint::Allow,
    ) {
        return Err(RenderError::Skia);
    }
    straight_capture(&mut pixels);
    let info = sk::ImageInfo::new(
        (w, h),
        sk::ColorType::RGBA8888,
        sk::AlphaType::Unpremul,
        None,
    );
    let image = sk::images::raster_from_data(&info, sk::Data::new_copy(&pixels), stride)
        .ok_or(RenderError::Skia)?;
    let png = image
        .encode(None, sk::EncodedImageFormat::PNG, None)
        .ok_or(RenderError::Skia)?;
    Ok(png.as_bytes().to_vec())
}

#[cfg(all(test, target_arch = "x86_64"))]
mod tests {
    use super::*;
    #[test]
    fn conversion_matches_independent_qimage_oracle() {
        // Generated by installed Qt QImage, retained by the island observer.
        let oracle = include_bytes!("../tests/fixtures/qt-unpremultiply.bin");
        for alpha in 0..=255u32 {
            for value in 0..=alpha {
                let mut pixel = [value as u8; 4];
                pixel[3] = alpha as u8;
                straight(&mut pixel);
                let expected = oracle[(alpha * 256 + value) as usize];
                assert_eq!(
                    pixel,
                    [expected, expected, expected, alpha as u8],
                    "{value}/{alpha}"
                );
            }
        }
    }
    #[test]
    fn single_pixel_conversion_matches_independent_qimage_oracle() {
        let single = include_bytes!("../tests/fixtures/qt-unpremultiply-single.bin");
        for a in 0..=255usize {
            for v in 0..=a {
                let mut pixel = [v as u8, v as u8, v as u8, a as u8];
                straight_capture(&mut pixel);
                let q = single[a * 256 + v];
                assert_eq!(pixel, [q, q, q, a as u8], "{v}/{a}");
            }
        }
    }
    #[test]
    fn narrow_multiline_capture_matches_independent_qimage_shapes() {
        let data = include_bytes!("../tests/fixtures/qt-capture-shapes.bin");
        let mut offset = 0;
        while offset < data.len() {
            let (w, h) = (data[offset] as usize, data[offset + 1] as usize);
            offset += 2;
            let mut pixels = [1, 2, 3, 10].repeat(w * h);
            let info = sk::ImageInfo::new(
                (w as i32, h as i32),
                sk::ColorType::RGBA8888,
                sk::AlphaType::Premul,
                None,
            );
            let image =
                sk::images::raster_from_data(&info, sk::Data::new_copy(&pixels), w * 4).unwrap();
            let png = qt_png(&image).unwrap();
            let image = sk::Image::from_encoded_with_alpha_type(
                sk::Data::new_copy(&png),
                sk::AlphaType::Unpremul,
            )
            .unwrap();
            let info = sk::ImageInfo::new(
                (w as i32, h as i32),
                sk::ColorType::RGBA8888,
                sk::AlphaType::Unpremul,
                None,
            );
            assert!(image.read_pixels(
                &info,
                &mut pixels,
                w * 4,
                (0, 0),
                sk::image::CachingHint::Allow
            ));
            assert_eq!(&pixels, &data[offset..offset + w * h * 4], "{w}x{h}");
            offset += w * h * 4;
        }
    }
    #[test]
    fn legacy_png_round_trip_recovers_every_valid_premultiplied_channel() {
        let oracle = include_bytes!("../tests/fixtures/qt-unpremultiply.bin");
        let mut pixels = vec![0u8; 256 * 256 * 4];
        for a in 0..=255usize {
            for v in 0..=a {
                pixels[(a * 256 + v) * 4..][..4]
                    .copy_from_slice(&[v as u8, v as u8, v as u8, a as u8]);
            }
        }
        let info = sk::ImageInfo::new(
            (256, 256),
            sk::ColorType::RGBA8888,
            sk::AlphaType::Premul,
            None,
        );
        let image = sk::images::raster_from_data(&info, sk::Data::new_copy(&pixels), 1024).unwrap();
        let legacy = image
            .encode(None, sk::EncodedImageFormat::PNG, None)
            .unwrap();
        let decoded = sk::Image::from_encoded(legacy).unwrap();
        let encoded = qt_png(&decoded).unwrap();
        let decoded = sk::Image::from_encoded_with_alpha_type(
            sk::Data::new_copy(&encoded),
            sk::AlphaType::Unpremul,
        )
        .unwrap();
        let info = sk::ImageInfo::new(
            (256, 256),
            sk::ColorType::RGBA8888,
            sk::AlphaType::Unpremul,
            None,
        );
        assert!(decoded.read_pixels(
            &info,
            &mut pixels,
            1024,
            (0, 0),
            sk::image::CachingHint::Allow
        ));
        for a in 0..=255usize {
            for v in 0..=a {
                let q = oracle[a * 256 + v];
                assert_eq!(
                    &pixels[(a * 256 + v) * 4..][..4],
                    &[q, q, q, a as u8],
                    "{v}/{a}"
                );
            }
        }
    }
    #[test]
    fn png_preserves_qt_half_ties_without_changing_premultiplied_capture() {
        let input = [
            1, 1, 2, 10, 109, 114, 135, 228, 1, 1, 2, 10, 109, 114, 135, 228,
        ];
        let info = sk::ImageInfo::new((4, 1), sk::ColorType::RGBA8888, sk::AlphaType::Premul, None);
        let image = sk::images::raster_from_data(&info, sk::Data::new_copy(&input), 16).unwrap();
        let png = qt_png(&image).unwrap();
        let decoded = sk::Image::from_encoded_with_alpha_type(
            sk::Data::new_copy(&png),
            sk::AlphaType::Unpremul,
        )
        .unwrap();
        let info = sk::ImageInfo::new(
            (4, 1),
            sk::ColorType::RGBA8888,
            sk::AlphaType::Unpremul,
            None,
        );
        let mut actual = [0; 16];
        assert!(decoded.read_pixels(
            &info,
            &mut actual,
            16,
            (0, 0),
            sk::image::CachingHint::Allow
        ));
        let mut expected = input;
        for pixel in expected.chunks_exact_mut(4) {
            straight(pixel);
        }
        assert_eq!(actual, expected);
        assert_eq!(&actual[..4], &[25, 25, 51, 10]);
        let default_decode = sk::Image::from_encoded(sk::Data::new_copy(&png)).unwrap();
        let cropped = default_decode
            .make_subset(None, sk::IRect::from_xywh(0, 0, 4, 1), Default::default())
            .unwrap();
        let reencoded = cropped
            .encode(None, sk::EncodedImageFormat::PNG, None)
            .unwrap();
        let decoded =
            sk::Image::from_encoded_with_alpha_type(reencoded, sk::AlphaType::Unpremul).unwrap();
        let one = sk::ImageInfo::new(
            (4, 1),
            sk::ColorType::RGBA8888,
            sk::AlphaType::Unpremul,
            None,
        );
        let mut cropped_pixel = [0u8; 16];
        assert!(decoded.read_pixels(
            &one,
            &mut cropped_pixel,
            16,
            (0, 0),
            sk::image::CachingHint::Allow
        ));
        assert_eq!(
            &cropped_pixel[..4],
            [26, 26, 51, 10],
            "a second Skia PNG encode reintroduces the half tie"
        );
        let corrected = qt_png(&cropped).unwrap();
        let decoded = sk::Image::from_encoded_with_alpha_type(
            sk::Data::new_copy(&corrected),
            sk::AlphaType::Unpremul,
        )
        .unwrap();
        assert!(decoded.read_pixels(
            &one,
            &mut cropped_pixel,
            16,
            (0, 0),
            sk::image::CachingHint::Allow
        ));
        assert_eq!(&cropped_pixel[..4], &[25, 25, 51, 10]);
    }
}
