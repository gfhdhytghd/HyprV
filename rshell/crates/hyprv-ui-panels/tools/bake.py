#!/usr/bin/env python3
"""Offline QtSvg baker for the panels (runtime stays Qt-free).

Reuses the bar's baker (crates/hyprv-ui-bar/tools/svg_bake.cpp, QSvgRenderer → QPainter
→ PNG) unchanged. Cache identity: (icon key, logical size, scale, colour) where the size
is what QQuickImage requests (sourceSize; rendered at qRound(size × scale) px) and the
colour is "source" (MultiEffect colourisation is applied at runtime, see icons_raster.rs).
Writes assets/baked/*.png, assets/baked/manifest.json and src/baked_data.rs.
"""
from pathlib import Path
import argparse, hashlib, json, os, shlex, subprocess

p = argparse.ArgumentParser()
p.add_argument('--scales', nargs='+', type=float, default=[1, 1.25, 1.5, 1.75, 2, 2.5, 3, 4])
a = p.parse_args()
root = Path(__file__).resolve().parents[1]
bar_tool = root.parent / 'hyprv-ui-bar/tools/svg_bake.cpp'
out = root / 'assets/baked'
out.mkdir(parents=True, exist_ok=True)
build = root / '.build'
build.mkdir(exist_ok=True)
binary = build / 'svg-bake'
flags = shlex.split(subprocess.check_output(['pkg-config', '--cflags', '--libs', 'Qt6Svg', 'Qt6Gui'], text=True))
subprocess.run(['c++', '-std=c++17', '-O2', str(bar_tool), '-o', str(binary), *flags], check=True)

home = Path.home()
qs = home / '.config/HyprV/quickshell'
icons = []  # (key, source path, logical sizes)
# ControlPanelToggle Image: sourceSize = max(32, round(iconImageSize * 2)), iconImageSize ∈ [18, 22]
icons.append(('assets/control-panel/light-dark.svg', qs / 'assets/control-panel/light-dark.svg', list(range(36, 45))))
icons.append(('assets/tray/network-wired-light.svg', qs / 'assets/tray/network-wired-light.svg', [24]))
# WifiIconWithFallback → IconImage: sourceSize = item size (24, or 16 for symbolic sources)
panel = home / '.local/share/icons/Fluent-light/24/panel'
symbolic = home / '.local/share/icons/Fluent-dark/symbolic/status'
names = [f'nm-signal-{b}{s}' for b in [0, 25, 50, 75, 100] for s in ['', '-secure']]
for n in names + ['network-wireless-offline', 'network-wireless-off', 'network-wireless-disconnected']:
    icons.append((f'24/panel/{n}.svg', panel / f'{n}.svg', [24]))
for n in names + ['network-wireless-hardware-disabled', 'network-wireless-disabled', 'network-wireless-disconnected', 'network-wired', 'network-wired-disconnected']:
    icons.append((f'symbolic/status/{n}-symbolic.svg', symbolic / f'{n}-symbolic.svg', [16]))

env = dict(os.environ, QT_QPA_PLATFORM='offscreen')
manifest = []
for key, src, sizes in icons:
    if not src.exists():
        print('missing', src)
        continue
    digest = hashlib.sha256(src.read_bytes()).hexdigest()
    stem = key.replace('/', '_').removesuffix('.svg')
    for size in sizes:
        for scale in a.scales:
            file = f'{stem}--{size}@{scale:g}--source.png'
            subprocess.run([str(binary), str(src), str(out / file), str(size), str(size), str(scale)], env=env, check=True)
            manifest.append(dict(icon=key, size=size, scale=scale, color='source', source_sha256=digest, file=file))
(out / 'manifest.json').write_text(json.dumps(manifest, indent=1) + '\n')
lines = ['// Generated by tools/bake.py. QtSvg is a build-time dependency only.',
         "pub fn bytes(icon: &str, size: u32, scale: f32, color: &str) -> Option<&'static [u8]> {",
         '    match (icon, size, (scale * 1000.).round() as u32, color) {']
for m in manifest:
    lines.append(f'        ("{m["icon"]}", {m["size"]}, {round(m["scale"] * 1000)}, "{m["color"]}") => Some(include_bytes!("../assets/baked/{m["file"]}")),')
lines += ['        _ => None,', '    }', '}']
(root / 'src/baked_data.rs').write_text('\n'.join(lines) + '\n')
print(f'Baked {len(manifest)} icons')
