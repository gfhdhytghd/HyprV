#!/usr/bin/env python3
"""QtSvg build/install-time baker. Runtime uses embedded PNG bytes only.
Cache identity includes source SHA, logical size, preferred output scale, and color.
"""
from pathlib import Path
import argparse,os,subprocess,shlex,hashlib,json
p=argparse.ArgumentParser();p.add_argument('--scales',nargs='+',type=float,default=[1,1.25,1.5,1.75,2,2.5,3,4]);a=p.parse_args()
root=Path(__file__).resolve().parents[1];out=root/'assets/baked';out.mkdir(exist_ok=True)
build=root/'.build';build.mkdir(exist_ok=True);binary=build/'svg-bake'
flags=shlex.split(subprocess.check_output(['pkg-config','--cflags','--libs','Qt6Svg','Qt6Gui'],text=True));subprocess.run(['c++','-std=c++17',str(root/'tools/svg_bake.cpp'),'-o',str(binary),*flags],check=True)
icons=[]
for name in ['control-panel-dark','control-panel-light']:icons.append((name,root/'assets'/f'{name}.svg',16,'source'))
icons.append(('network-wired-light',root/'assets/network-wired-light.svg',24,'source'))
for dark in [False,True]:
 theme=Path.home()/'.local/share/icons'/('Fluent-dark'if dark else'Fluent-light')
 names=['network-wireless-hardware-disabled','network-wireless-disabled','network-wireless-offline','network-wireless-off','network-wireless-disconnected','network-wired']
 names +=[f'nm-signal-{b}{s}'for b in [0,25,50,75,100]for s in['','-secure']]
 for name in names:
  key=name+('-symbolic'if dark else'');source=theme/('symbolic/status'if dark else'24/panel')/(key+'.svg')
  if source.exists():icons.append((key,source,16 if dark else 24,'source'))
# Qt Canvas inverse corners use the same QPainter path rasterizer as QtSvg.
corner=root/'assets/corner-top-left.svg';corner.write_text('<svg xmlns="http://www.w3.org/2000/svg" width="27" height="27" viewBox="0 0 27 27"><path fill="#000000" d="M0 0 H27 A27 27 0 0 0 0 27 Z"/></svg>\n');
for name in ['top-left','top-right','bottom-left','bottom-right']:icons.append(('corner-'+name,'@corner-'+name,27,'000000ff'))
manifest=[];env=dict(os.environ);env['QT_QPA_PLATFORM']='offscreen'
for key,source,size,color in icons:
 digest=hashlib.sha256(source.read_bytes() if isinstance(source,Path) else (root/'tools/svg_bake.cpp').read_bytes()).hexdigest()
 for scale in a.scales:
  raster_size=32 if key.startswith('control-panel-') else size
  file=f'{key}--{size}@{scale:g}--{color}.png';subprocess.run([str(binary),str(source),str(out/file),str(raster_size),str(raster_size),str(scale)],env=env,check=True);manifest.append(dict(icon=key,size=size,scale=scale,color=color,raster_size=raster_size,raster_scale=scale,source_sha256=digest,file=file))
(out/'manifest.json').write_text(json.dumps(manifest,indent=2))
(out/'provenance.json').write_text(json.dumps(dict(qt_svg_version=subprocess.check_output(['pkg-config','--modversion','Qt6Svg'],text=True).strip(),tool_sha256=hashlib.sha256((root/'tools/svg_bake.cpp').read_bytes()).hexdigest(),scales=a.scales,entries=len(manifest),runtime_qt=False),indent=2))
lines=['// Generated by tools/bake.py. QtSvg is a build/install-time dependency only.','pub fn bytes(icon:&str,size:u32,scale:f32,color:&str)->Option<&\'static [u8]>{','match (icon,size,(scale*1000.).round()as u32,color){']
for m in manifest:lines.append(f'("{m["icon"]}",{m["size"]},{round(m["scale"]*1000)},"{m["color"]}")=>Some(include_bytes!("../assets/baked/{m["file"]}")),')
lines+=['_=>None,','}','}'];(root/'src/baked_data.rs').write_text('\n'.join(lines)+'\n');print(f'Baked {len(manifest)} icons')

subprocess.run(['rustfmt','--edition','2021',str(root/'src/baked_data.rs')],check=True)
